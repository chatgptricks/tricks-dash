import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';

const source = fs.readFileSync('public/user-preferences.js', 'utf8');
const cache = new Map([['sentient.lang', 'en'], ['sentient.language', 'en'], ['sentient.language.pending', 'en']]);
const timers = [];
const listeners = new Map();
const events = [];
const storage = { getItem: key => cache.get(key) ?? null, setItem: (key, value) => cache.set(key, String(value)), removeItem: key => cache.delete(key), key: index => [...cache.keys()][index], get length() { return cache.size; } };
const window = { setTimeout: callback => (timers.push(callback), timers.length), addEventListener: (name, callback) => listeners.set(name, callback), dispatchEvent: event => events.push(event), CustomEvent: class { constructor(type, options) { this.type = type; this.detail = options.detail; } } };
vm.runInNewContext(source, { window, localStorage: storage, fetch: () => { throw new Error('Unexpected network access'); } });
const requests = [];
let fail = false;
const transport = async (_url, options) => {
  if (!options) return { ok: true, json: async () => ({ preferences: { language: 'es' } }) };
  requests.push(JSON.parse(options.body).preferences);
  return { ok: !fail, status: fail ? 503 : 200 };
};
const runTimers = async () => { const batch = timers.splice(0); for (const callback of batch) callback(); await new Promise(resolve => setImmediate(resolve)); };
const prefs = await window.SentientPreferences.load({ email: 'fixture@example.test', fetch: transport });
assert.equal(prefs.language, 'en', 'an explicit guide choice survives an older server preference');
assert.equal(events.at(-1).detail.language, 'en');
await runTimers();
assert.equal(requests.at(-1).language, 'en');
assert.equal(cache.has('sentient.language.pending'), false, 'confirmed persistence clears the navigation marker');
fail = true;
window.SentientPreferences.save('language', 'es');
await runTimers();
assert.equal(cache.get('sentient.language.pending'), 'es', 'a transient failure retains the selected language for the next page');
fail = false;
await runTimers();
assert.equal(cache.has('sentient.language.pending'), false);
cache.set('sentient.language.pending', 'en');
listeners.get('storage')({ key: 'sentient.language.pending', newValue: 'en' });
assert.equal(window.SentientPreferences.get('language'), 'en', 'a guide choice in another tab updates the current user preference');
await runTimers();
assert.equal(requests.at(-1).language, 'en');
console.log('PASS language preference persistence across guide navigation, server restoration, retries and tabs');
